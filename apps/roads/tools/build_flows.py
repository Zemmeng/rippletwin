#!/usr/bin/env python3
"""Purpose: turn raw/cbd_VSDATA_*.csv (SCATS: 96 fifteen-minute counts per detector per day) into public/<area>/flows.json (format: PRD 5.2).

Usage:
  python3 apps/roads/tools/build_flows.py [--area cbd] [--from 2026-08-01] [--to 2026-09-27]
Prerequisites: network.json generated by tools/build_network.py; raw/cbd_VSDATA_*.csv extracted by tools/fetch_scats.py --range
Exit code: 0 success; 1 network.json missing or no SCATS files at all
Dependencies: Python standard library only.

Where each link's flow comes from (recorded in method):
  detector_map   the site is in DETECTOR_MAP and the approach direction matches: the sum of those detectors (from the configuration sheet; most accurate)
  site_split     the link ends at a junction with SCATS data: lanes x "mean hourly flow of this junction's lane detectors"
                 (signal detectors are roughly one per lane, so "mean per detector" ~ "mean per lane"; a lane detector has a daily count
                  >= LANE_SHARE of the junction's busiest detector and >= MIN_DAILY, see per_lane_profile)
  street_interp  the mean of adjacent upstream/downstream links on the same street, propagated along the street
  class_default  median per-lane flow of measured links of the same road class x lanes
"""
import argparse, csv, datetime, glob, json, math, os, statistics, sys

MOD = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HOLIDAYS = {'2026-09-25'}   # Victorian public holiday (the day before the AFL Grand Final)
MIN_DAILY = 300            # detectors averaging fewer than this per weekday are not counted (pedestrian buttons, faulty detectors)
LANE_SHARE = 0.5           # a "lane detector" needs a daily count >= this share of the junction's busiest detector
INTERP_ROUNDS = 30         # maximum number of links to propagate along a street
# site -> {approach heading: [detector numbers]}; from the plan on page 2 of the configuration sheet (2921 checked against DET in apps/sim/tools/build_demand.py)
DETECTOR_MAP = {'2921': {'E': [7], 'W': [5], 'S': [3]}}


def kind(day):
    return 'we' if datetime.date.fromisoformat(day).weekday() >= 5 else 'wd'


def heading(geom):
    """Heading of the link's last segment: E / N / W / S (by 45-degree sectors)."""
    (la1, lo1), (la2, lo2) = geom[-2], geom[-1]
    ang = math.degrees(math.atan2(la2 - la1, (lo2 - lo1) * math.cos(math.radians(la1)))) % 360
    return 'ENWS'[int(((ang + 45) % 360) // 90)]


def load_detectors(files, d_from, d_to):
    """-> {site: {detector: {'wd'|'we': [24 hourly means]}}}, days used"""
    acc, days = {}, {'wd': set(), 'we': set()}
    for p in files:
        for r in csv.reader(open(p, encoding='utf-8-sig')):
            if not r or not r[2].isdigit():
                continue
            day = r[1][:10]
            if not (d_from <= day <= d_to) or day in HOLIDAYS:
                continue
            k = kind(day); days[k].add(day)
            v = [int(x) for x in r[3:99]]
            slot = acc.setdefault(r[0], {}).setdefault(int(r[2]), {'wd': [[0, 0] for _ in range(24)], 'we': [[0, 0] for _ in range(24)]})[k]
            for h in range(24):
                q = v[4 * h:4 * h + 4]
                if min(q) >= 0:  # negative = fault or missing; if any slot is missing the whole hour is dropped
                    slot[h][0] += sum(q); slot[h][1] += 1
    out = {}
    for site, dets in acc.items():
        for det, byk in dets.items():
            out.setdefault(site, {})[det] = {k: [s / n if n else None for s, n in byk[k]] for k in ('wd', 'we')}
    return out, {k: sorted(v) for k, v in days.items()}


def fill(arr):
    """Fill hours that are missing entirely from the neighbouring hours."""
    if all(x is None for x in arr):
        return [0.0] * 24
    out = list(arr)
    for h in range(24):
        if out[h] is None:
            for d in range(1, 24):
                cand = [x for x in (arr[(h - d) % 24], arr[(h + d) % 24]) if x is not None]
                if cand:
                    out[h] = sum(cand) / len(cand); break
    return out


def per_lane_profile(dets):
    """Hourly mean of the detectors that look like traffic lanes -> {'wd': [24], 'we': [24]}; None if there are none.
    Only detectors with a daily count >= LANE_SHARE of the junction's busiest detector count: tram, pedestrian-button and most bike
    detectors carry little flow and would halve the per-lane flow if averaged in
    (2921: all valid detectors average about 3.3k a day, lane detectors 5 and 7 carry 6.0-7.0k; the 50% rule gives about 6.2k)."""
    daily = {k: sum(x or 0 for x in d['wd']) for k, d in dets.items()}
    top = max(daily.values(), default=0)
    active = [d for k, d in dets.items() if daily[k] >= max(MIN_DAILY, LANE_SHARE * top)]
    if not active:
        return None
    return {k: [statistics.mean(fill(d[k])[h] for d in active) for h in range(24)] for k in ('wd', 'we')}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--area', default='cbd')
    ap.add_argument('--raw', default=os.path.join(MOD, 'raw'))
    ap.add_argument('--from', dest='d_from', default='2026-08-01')
    ap.add_argument('--to', dest='d_to', default='2026-09-27')
    a = ap.parse_args()
    np_ = os.path.join(MOD, 'public', a.area, 'network.json')
    if not os.path.exists(np_):
        print('❌ %s not found: run tools/build_network.py first' % np_); sys.exit(1)
    files = sorted(glob.glob(os.path.join(a.raw, 'cbd_VSDATA_*.csv')))
    if not files:
        print('❌ no cbd_VSDATA_*.csv in raw/: run tools/fetch_scats.py --range %s..%s first' % (a.d_from, a.d_to)); sys.exit(1)
    net = json.load(open(np_, encoding='utf-8'))
    links = {l['id']: l for l in net['links']}
    node_site = {n['id']: n['signal'] for n in net['nodes'] if n.get('signal')}

    dets, days = load_detectors(files, a.d_from, a.d_to)
    if not days['wd'] or not days['we']:
        print('⚠️  %d weekdays, %d weekend days: if one kind is missing, the other is used instead' % (len(days['wd']), len(days['we'])))
    for site in dets.values():
        for d in site.values():
            if not days['we']:
                d['we'] = d['wd']
            if not days['wd']:
                d['wd'] = d['we']

    flows, method = {'wd': {}, 'we': {}}, {}

    def put(lid, prof, m, scale=1.0):
        for k in ('wd', 'we'):
            flows[k][lid] = [max(0.0, x * scale) for x in prof[k]]
        method[lid] = m

    # 1) Approach links: detector_map or site_split
    lane_prof = {s: per_lane_profile(d) for s, d in dets.items()}
    for lid, l in links.items():
        site = node_site.get(l['to'])
        if not site or node_site.get(l['from']) == site or site not in dets:
            continue  # the end node is not a signalised junction with data, or this is a connector inside one junction
        dm = DETECTOR_MAP.get(site, {}).get(heading(l['geometry']))
        if dm and all(d in dets[site] for d in dm):
            put(lid, {k: [sum(fill(dets[site][d][k])[h] for d in dm) for h in range(24)] for k in ('wd', 'we')}, 'detector_map')
        elif lane_prof.get(site):
            put(lid, lane_prof[site], 'site_split', l['lanes'])

    # 2) Interpolate upstream/downstream along the same street
    out_by, in_by = {}, {}
    for lid, l in links.items():
        out_by.setdefault(l['from'], []).append(lid); in_by.setdefault(l['to'], []).append(lid)

    def same_street(lid):
        l = links[lid]
        if not l['name']:
            return []
        nb = [x for x in out_by.get(l['to'], []) if links[x]['to'] != l['from']]
        nb += [x for x in in_by.get(l['from'], []) if links[x]['from'] != l['to']]
        return [x for x in nb if links[x]['name'] == l['name']]

    for _ in range(INTERP_ROUNDS):
        new = {}
        for lid in links:
            if lid in method:
                continue
            known = [x for x in same_street(lid) if x in method]
            if known:
                # average the per-lane flow, then multiply by this link's lanes
                new[lid] = {k: [statistics.mean(flows[k][x][h] / links[x]['lanes'] for x in known) * links[lid]['lanes']
                                for h in range(24)] for k in ('wd', 'we')}
        if not new:
            break
        for lid, prof in new.items():
            put(lid, prof, 'street_interp')

    # 3) Road-class defaults
    measured = [x for x, m in method.items() if m in ('detector_map', 'site_split')]
    by_class = {}
    for x in measured:
        by_class.setdefault(links[x]['highway'], []).append(x)
    all_med = {k: [statistics.median(flows[k][x][h] / links[x]['lanes'] for x in measured) for h in range(24)] for k in ('wd', 'we')}
    for lid, l in links.items():
        if lid in method:
            continue
        pool = by_class.get(l['highway'])
        med = {k: [statistics.median(flows[k][x][h] / links[x]['lanes'] for x in pool) for h in range(24)] for k in ('wd', 'we')} if pool else all_med
        put(lid, med, 'class_default', l['lanes'])

    n_meas = sum(1 for m in method.values() if m in ('detector_map', 'site_split'))
    out = {
        'version': 1, 'unit': 'veh/h',
        'period': '%s..%s (excluding days with missing data and the public holiday %s)' % (a.d_from, a.d_to, ', '.join(sorted(HOLIDAYS))),
        'days_used': {k: len(v) for k, v in days.items()},
        'sources': ['Traffic Signal Volume Data, DTP Victoria (CC BY 4.0)'],
        'assumptions': {'min_daily_active_detector': MIN_DAILY, 'lane_detector_share_of_site_max': LANE_SHARE,
                        'detector_map_sites': sorted(DETECTOR_MAP),
                        'site_split': 'lanes × mean hourly flow of the junction lane detectors (daily count ≥ 50% of the busiest detector)'},
        'days': {k: {lid: [round(x) for x in flows[k][lid]] for lid in links} for k in ('wd', 'we')},
        'method': {lid: method[lid] for lid in links},
        'coverage': {'links': len(links), 'measured': n_meas, 'estimated': len(links) - n_meas},
    }
    p = os.path.join(MOD, 'public', a.area, 'flows.json')
    with open(p, 'w', encoding='utf-8') as f:
        json.dump(out, f, ensure_ascii=False, separators=(',', ':'))
    cnt = {}
    for m in method.values():
        cnt[m] = cnt.get(m, 0) + 1
    print('✅ flows.json: %d links, %s; %d weekdays, %d weekend days; %d KB'
          % (len(links), ', '.join('%s %d' % kv for kv in sorted(cnt.items())), len(days['wd']), len(days['we']), os.path.getsize(p) // 1024))


if __name__ == '__main__':
    main()
